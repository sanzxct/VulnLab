#!/usr/bin/env bash
# ByteBazaar launcher.
#
# Auto-picks free host ports (preferring 8080 for the app and 8081 for staging;
# scans upward if those are taken), writes them to .env so every subsequent
# `docker compose` command reuses the same mapping, then brings the stack up.
#
# Needs only bash + Docker — no Python/Node/etc. on the host.
#
#   ./scripts/start.sh            # build + start on auto-selected ports
#   ./scripts/start.sh --no-build # skip the image build (pass extra compose args)
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

# True (0) if something is already listening on 127.0.0.1:$1.
port_in_use() {
  (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null && { exec 3>&- 3<&-; return 0; } || return 1
}

# First free port at or above $1.
find_free_port() {
  local p="$1"
  while port_in_use "$p"; do p=$((p + 1)); done
  echo "$p"
}

APP_PORT="$(find_free_port "${APP_PORT:-8080}")"

# Staging starts one above the app port (and never below 8081).
staging_base=8081
if [ "$((APP_PORT + 1))" -gt "$staging_base" ]; then staging_base=$((APP_PORT + 1)); fi
STAGING_PORT="$(find_free_port "$staging_base")"

cat > .env <<EOF
# Auto-generated by scripts/start.sh — host port mappings for docker compose.
# Delete this file (or edit it) to change ports; re-run scripts/start.sh to regenerate.
APP_PORT=$APP_PORT
STAGING_PORT=$STAGING_PORT
EOF

if [ "$APP_PORT" != "8080" ]; then
  echo "note: port 8080 was taken — using $APP_PORT for the app instead."
fi
echo "Starting ByteBazaar: app -> :$APP_PORT, staging -> :$STAGING_PORT"

# Default to a build unless the caller passes their own compose args.
if [ "$#" -eq 0 ]; then
  docker compose up -d --build
else
  docker compose up -d "$@"
fi
status=$?

if [ "$status" -eq 0 ]; then
  echo
  echo "  ByteBazaar is up:"
  echo "    App:     http://localhost:$APP_PORT"
  echo "    Staging: http://localhost:$STAGING_PORT"
  echo "    Stop:    docker compose down    (add -v to wipe the database)"
fi
exit "$status"
